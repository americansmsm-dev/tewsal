-- ------------------------------------------------------------
-- منع تكرار حسابات الشركة
-- ------------------------------------------------------------
-- Postgres بيعتبر كل NULL مختلف عن التاني، فالفهرس الفريد
-- على (code, owner_id) **مبيمنعش** تكرار حسابات الشركة
-- (اللي owner_id بتاعها NULL).
--
-- من غير الفهرس ده «إيراد الشحن» يقدر يتكرر مرتين، وأرصدة
-- الشركة تتقسم على حسابين من غير ما حد ياخد باله.
--
CREATE UNIQUE INDEX "accounts_code_company_uq" ON "accounts" USING btree ("code") WHERE "accounts"."owner_id" IS NULL;
