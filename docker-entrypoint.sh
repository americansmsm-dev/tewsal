#!/bin/sh
# ============================================================
#  Tewsal — إقلاع الحاوية
# ------------------------------------------------------------
#  بيطبّق الـ migrations ثم البذور (idempotent) قبل تشغيل
#  السيرفر. مصمّم لنسخة واحدة (staging). لو اتعدّينا لأكتر من
#  نسخة، نرجّع الهجرة لخطوة نشر منفصلة (منع تسابق النسخ).
#  السيد آمن للتكرار — بيتخطى أي حاجة موجودة.
# ============================================================
set -e

TSX="node_modules/.bin/tsx"

echo "→ [tewsal] تطبيق الـ migrations..."
"$TSX" scripts/migrate.ts

echo "→ [tewsal] البذور (idempotent)..."
"$TSX" scripts/seed.ts

echo "→ [tewsal] تشغيل السيرفر..."
exec node server.js
